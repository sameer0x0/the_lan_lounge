/**
 * UNO rules engine. Pure functions, no I/O, no timers.
 *
 * Every action takes the current state and returns a NEW state (the input is never mutated), or throws
 * a `UnoError` with a message that is safe to show the player. The server owns the state; phones only
 * ever see `unoViewFor(...)`, so nobody else's hand leaks.
 *
 * Implements the core rules in docs/SPEC.md "Game 2: UNO". Not implemented yet (Phase 6 admin toggles):
 * house rules (stacking, draw-until-play, 7-0, jump-in), turn timer scheduling, undo, force-draw.
 */
import { shuffle, type Rng } from './random';

export type UnoColor = 'red' | 'yellow' | 'green' | 'blue';
export type CardKind = 'number' | 'skip' | 'reverse' | 'draw2' | 'wild' | 'wild4';

export interface UnoCard {
  /** Unique within a game (0-107 with one deck, 0-215 with two), so the client can say exactly which card it plays. */
  id: number;
  /** Wild cards are always 'wild' here; the colour a player picks lives in `UnoState.activeColor`. */
  color: UnoColor | 'wild';
  kind: CardKind;
  /** 0-9 for number cards, null otherwise. */
  value: number | null;
}

export const UNO_COLORS: readonly UnoColor[] = ['red', 'yellow', 'green', 'blue'];
export const MIN_PLAYERS = 2;
export const MAX_PLAYERS = 20;
export const HAND_SIZE = 7;
export const DEFAULT_TARGET_SCORE = 500;

export class UnoError extends Error {}
const fail = (msg: string): never => {
  throw new UnoError(msg);
};

// ---- deck ------------------------------------------------------------------

export const CARDS_PER_DECK = 108;
/** One deck deals up to 10 players. Bigger tables shuffle in a second deck (the usual rule for large groups). */
export const MAX_PLAYERS_ONE_DECK = 10;
export const deckCountFor = (playerCount: number) => (playerCount <= MAX_PLAYERS_ONE_DECK ? 1 : 2);

/**
 * The standard 108 cards: per colour one 0, two each of 1-9, Skip, Reverse, Draw Two; plus 4 Wild, 4 Wild Draw Four.
 * `decks` > 1 repeats the set. Ids stay unique across the whole shoe (0-107, then 108-215...), while identical
 * faces share one image file.
 */
export function buildDeck(decks = 1): UnoCard[] {
  const cards: UnoCard[] = [];
  let id = 0;
  const add = (color: UnoCard['color'], kind: CardKind, value: number | null, copies: number) => {
    for (let i = 0; i < copies; i++) cards.push({ id: id++, color, kind, value });
  };
  for (let d = 0; d < decks; d++) {
    for (const color of UNO_COLORS) {
      add(color, 'number', 0, 1);
      for (let v = 1; v <= 9; v++) add(color, 'number', v, 2);
      add(color, 'skip', null, 2);
      add(color, 'reverse', null, 2);
      add(color, 'draw2', null, 2);
    }
    add('wild', 'wild', null, 4);
    add('wild', 'wild4', null, 4);
  }
  return cards;
}

/** Where the image for a card lives (served from apps/web/public). Generated by `npm run cards`. */
export const CARD_BACK = '/cards/back.svg';
export function cardAsset(card: Pick<UnoCard, 'color' | 'kind' | 'value'>): string {
  if (card.kind === 'wild') return '/cards/wild.svg';
  if (card.kind === 'wild4') return '/cards/wild4.svg';
  const face = card.kind === 'number' ? String(card.value) : card.kind;
  return `/cards/${card.color}-${face}.svg`;
}

/** Points a card is worth in the loser's hand when someone wins a round. */
export function cardPoints(card: UnoCard): number {
  if (card.kind === 'number') return card.value ?? 0;
  if (card.kind === 'wild' || card.kind === 'wild4') return 50;
  return 20;
}

// ---- state -----------------------------------------------------------------

export interface UnoSettings {
  /** First to reach this many points wins the game. Spec default 500; the host can lower it. */
  targetScore: number;
}

export interface UnoPlayerState {
  id: string;
  hand: UnoCard[];
  score: number;
  /** True once the player has pressed UNO while holding 1-2 cards. Resets when they hold 3+. */
  calledUno: boolean;
}

export type UnoPhase = 'playing' | 'challenge' | 'roundOver' | 'gameOver';

export type UnoEvent =
  | { kind: 'play'; playerId: string; card: UnoCard; color: UnoColor | null }
  | { kind: 'draw'; playerId: string; count: number; reason: 'turn' | 'draw2' | 'draw4' | 'challenge' | 'catch' | 'skipped' }
  | { kind: 'pass'; playerId: string }
  | { kind: 'skip'; playerId: string }
  | { kind: 'reverse' }
  | { kind: 'challenge'; challengerId: string; targetId: string; bluffing: boolean }
  | { kind: 'uno'; playerId: string }
  | { kind: 'catch'; catcherId: string; targetId: string }
  | { kind: 'reshuffle' }
  | { kind: 'round'; winnerId: string; points: number };

export interface UnoState {
  settings: UnoSettings;
  phase: UnoPhase;
  round: number;
  players: UnoPlayerState[];
  /** Cards are taken from the END of the array. */
  drawPile: UnoCard[];
  /** Top card is the LAST element. */
  discard: UnoCard[];
  /** Colour in force. null only right after an opening Wild: the first player may then play anything. */
  activeColor: UnoColor | null;
  direction: 1 | -1;
  /** Index into `players` of whoever must act (in 'challenge', the player who may challenge). */
  current: number;
  dealer: number;
  /** Id of a card the current player just drew and may still play; they can only play it or pass. */
  drawn: number | null;
  /** Set while a Wild Draw Four waits for the next player to challenge or accept. */
  challenge: { fromId: string; targetId: string; bluffing: boolean } | null;
  /** Player who dropped to one card without calling UNO and can still be caught. */
  unoPending: string | null;
  roundWinnerId: string | null;
  roundPoints: number;
  gameWinnerId: string | null;
  /** Most recent events (capped), for the "Nadia played Draw Two on Rafi" line. */
  log: UnoEvent[];
}

const LOG_LIMIT = 30;

/** State is plain JSON (it is also snapshotted to SQLite), so a JSON round-trip is a safe deep copy. */
const clone = (s: UnoState): UnoState => JSON.parse(JSON.stringify(s));

const log = (s: UnoState, e: UnoEvent) => {
  s.log.push(e);
  if (s.log.length > LOG_LIMIT) s.log.splice(0, s.log.length - LOG_LIMIT);
};

const topCard = (s: UnoState) => s.discard[s.discard.length - 1]!;
/** Index of the player `k` places along the current direction. */
const step = (s: UnoState, from: number, k = 1) => {
  const n = s.players.length;
  return (((from + s.direction * k) % n) + n) % n;
};
const indexOf = (s: UnoState, playerId: string) => {
  const i = s.players.findIndex((p) => p.id === playerId);
  return i < 0 ? fail('You are not in this game') : i;
};
const refreshUnoFlag = (p: UnoPlayerState) => {
  if (p.hand.length > 2) p.calledUno = false;
};

// ---- setup -----------------------------------------------------------------

/** Starts a game: shuffles, deals 7 each and flips the opening card. Player order = seating order. 11-20 players play with two decks. */
export function createUnoGame(
  playerIds: readonly string[],
  settings: Partial<UnoSettings> = {},
  rng: Rng = Math.random,
): UnoState {
  if (playerIds.length < MIN_PLAYERS || playerIds.length > MAX_PLAYERS) {
    fail(`UNO needs ${MIN_PLAYERS}-${MAX_PLAYERS} players`);
  }
  if (new Set(playerIds).size !== playerIds.length) fail('Duplicate player');
  const targetScore = settings.targetScore ?? DEFAULT_TARGET_SCORE;
  if (!Number.isInteger(targetScore) || targetScore < 1) fail('Target score must be a positive whole number');

  const s: UnoState = {
    settings: { targetScore },
    phase: 'playing',
    round: 0,
    players: playerIds.map((id) => ({ id, hand: [], score: 0, calledUno: false })),
    drawPile: [],
    discard: [],
    activeColor: null,
    direction: 1,
    current: 0,
    dealer: playerIds.length - 1, // so seat 0 plays first in round 1
    drawn: null,
    challenge: null,
    unoPending: null,
    roundWinnerId: null,
    roundPoints: 0,
    gameWinnerId: null,
    log: [],
  };
  startRound(s, rng);
  return s;
}

/** Deals a fresh round into `s` (mutates; only called on a private copy). Scores are kept. */
function startRound(s: UnoState, rng: Rng) {
  const n = s.players.length;
  s.round += 1;
  s.phase = 'playing';
  s.direction = 1;
  s.drawn = null;
  s.challenge = null;
  s.unoPending = null;
  s.roundWinnerId = null;
  s.roundPoints = 0;
  for (const p of s.players) {
    p.hand = [];
    p.calledUno = false;
  }

  s.drawPile = shuffle(buildDeck(deckCountFor(n)), rng);
  for (let i = 0; i < HAND_SIZE; i++) for (const p of s.players) p.hand.push(s.drawPile.pop()!);

  // A Wild Draw Four can't open the game: shuffle it back in and flip again.
  let start = s.drawPile.pop()!;
  while (start.kind === 'wild4') {
    s.drawPile = shuffle([...s.drawPile, start], rng);
    start = s.drawPile.pop()!;
  }
  s.discard = [start];
  s.activeColor = start.color === 'wild' ? null : start.color;

  // Seat after the dealer starts; other opening action cards hit that first player.
  s.current = step(s, s.dealer);
  switch (start.kind) {
    case 'skip':
      log(s, { kind: 'skip', playerId: s.players[s.current]!.id });
      s.current = step(s, s.current);
      break;
    case 'reverse':
      log(s, { kind: 'reverse' });
      if (n === 2) {
        s.current = step(s, s.current); // acts as Skip with two players
      } else {
        s.direction = -1;
        s.current = s.dealer; // play runs the other way, starting with the dealer
      }
      break;
    case 'draw2': {
      const victim = s.current;
      drawInto(s, victim, 2, 'draw2', rng);
      s.current = step(s, victim);
      break;
    }
    default: // numbers and Wild: first player plays normally (after an opening Wild, any card is legal)
      break;
  }
}

/** Next round after a round ends but nobody has reached the target. */
export function nextUnoRound(state: UnoState, rng: Rng = Math.random): UnoState {
  if (state.phase !== 'roundOver') fail('The round is not over');
  const s = clone(state);
  s.dealer = (s.dealer + 1) % s.players.length;
  startRound(s, rng);
  return s;
}

// ---- drawing ---------------------------------------------------------------

/** Takes up to `count` cards, reshuffling the discard pile (except its top card) when the draw pile runs dry. */
function takeCards(s: UnoState, count: number, rng: Rng): UnoCard[] {
  const out: UnoCard[] = [];
  while (out.length < count) {
    if (s.drawPile.length === 0) {
      if (s.discard.length <= 1) break; // nothing left anywhere
      const top = s.discard.pop()!;
      s.drawPile = shuffle(s.discard, rng);
      s.discard = [top];
      log(s, { kind: 'reshuffle' });
    }
    out.push(s.drawPile.pop()!);
  }
  return out;
}

function drawInto(s: UnoState, playerIndex: number, count: number, reason: Extract<UnoEvent, { kind: 'draw' }>['reason'], rng: Rng) {
  const p = s.players[playerIndex]!;
  const cards = takeCards(s, count, rng);
  p.hand.push(...cards);
  refreshUnoFlag(p);
  log(s, { kind: 'draw', playerId: p.id, count: cards.length, reason });
  return cards;
}

// ---- legality --------------------------------------------------------------

/** Can `card` go on the current top card? (Ignores whose turn it is.) */
export function isPlayable(state: UnoState, card: UnoCard): boolean {
  if (card.color === 'wild') return true;
  if (state.activeColor === null || card.color === state.activeColor) return true;
  const top = topCard(state);
  if (top.kind === 'number') return card.kind === 'number' && card.value === top.value;
  return card.kind === top.kind; // same symbol: Skip on Skip, Reverse on Reverse, Draw Two on Draw Two
}

/** Ids the given player may play right now (empty when it's not their move). */
export function legalPlays(state: UnoState, playerId: string): number[] {
  if (state.phase !== 'playing') return [];
  const me = state.players[state.current]!;
  if (me.id !== playerId) return [];
  if (state.drawn !== null) return [state.drawn];
  return me.hand.filter((c) => isPlayable(state, c)).map((c) => c.id);
}

function requireTurn(s: UnoState, playerId: string, phase: UnoPhase): number {
  const i = indexOf(s, playerId);
  if (s.phase === 'roundOver' || s.phase === 'gameOver') fail('The round is over');
  if (s.phase !== phase) fail(phase === 'challenge' ? 'There is nothing to challenge' : 'Respond to the Wild Draw Four first');
  if (s.current !== i) fail('It is not your turn');
  return i;
}

// ---- actions ---------------------------------------------------------------

/** Plays a card from your hand. Wilds need `chosenColor`. */
export function playCard(
  state: UnoState,
  playerId: string,
  cardId: number,
  chosenColor?: UnoColor,
  rng: Rng = Math.random,
): UnoState {
  const s = clone(state);
  const idx = requireTurn(s, playerId, 'playing');
  const player = s.players[idx]!;

  if (s.drawn !== null && s.drawn !== cardId) fail('You can only play the card you just drew, or pass');
  const at = player.hand.findIndex((c) => c.id === cardId);
  if (at < 0) fail('You do not have that card');
  const card = player.hand[at]!;
  if (!isPlayable(s, card)) fail("That card doesn't match the top card");
  const isWild = card.color === 'wild';
  if (isWild && !(chosenColor && UNO_COLORS.includes(chosenColor))) fail('Choose a colour for the Wild');

  const previousColor = s.activeColor;
  s.unoPending = null; // the player after the last UNO slip-up has now acted
  s.drawn = null;
  player.hand.splice(at, 1);
  s.discard.push(card);
  s.activeColor = isWild ? chosenColor! : (card.color as UnoColor);
  log(s, { kind: 'play', playerId, card, color: s.activeColor });

  // Dropping to one card without having pressed UNO leaves you catchable.
  if (player.hand.length === 1 && !player.calledUno) s.unoPending = playerId;
  refreshUnoFlag(player);

  const lastCard = player.hand.length === 0;
  switch (card.kind) {
    case 'skip': {
      log(s, { kind: 'skip', playerId: s.players[step(s, idx)]!.id });
      s.current = step(s, idx, 2);
      break;
    }
    case 'reverse': {
      s.direction = s.direction === 1 ? -1 : 1;
      log(s, { kind: 'reverse' });
      s.current = s.players.length === 2 ? idx : step(s, idx); // Skip with two players
      break;
    }
    case 'draw2': {
      const victim = step(s, idx);
      drawInto(s, victim, 2, 'draw2', rng);
      s.current = step(s, idx, 2);
      break;
    }
    case 'wild4': {
      const victim = step(s, idx);
      if (lastCard) {
        // Winning on a Draw Four: no time to bluff-check, the next player just takes the 4.
        drawInto(s, victim, 4, 'draw4', rng);
        s.current = step(s, idx, 2);
      } else {
        // The Draw Four is only "legal" with no card of the old colour; the next player may call the bluff.
        const bluffing = previousColor !== null && player.hand.some((c) => c.color === previousColor);
        s.phase = 'challenge';
        s.challenge = { fromId: playerId, targetId: s.players[victim]!.id, bluffing };
        s.current = victim;
      }
      break;
    }
    default: // number, wild
      s.current = step(s, idx);
  }

  if (lastCard) finishRound(s, idx);
  return s;
}

/**
 * Draw a card. On your turn: take one; if it can be played you may play it (or `passTurn`), otherwise your
 * turn ends. When a Wild Draw Four is aimed at you: accept it (take 4, lose your turn).
 */
export function drawCard(state: UnoState, playerId: string, rng: Rng = Math.random): UnoState {
  const s = clone(state);
  const i = indexOf(s, playerId);
  if (s.phase === 'challenge') {
    requireTurn(s, playerId, 'challenge');
    s.unoPending = null;
    drawInto(s, i, 4, 'draw4', rng);
    s.challenge = null;
    s.phase = 'playing';
    s.current = step(s, i);
    return s;
  }
  requireTurn(s, playerId, 'playing');
  if (s.drawn !== null) fail('You already drew. Play that card or pass');
  s.unoPending = null;
  const [card] = drawInto(s, i, 1, 'turn', rng);
  if (card && isPlayable(s, card)) s.drawn = card.id;
  else s.current = step(s, i);
  return s;
}

/** After drawing a playable card, decline to play it. */
export function passTurn(state: UnoState, playerId: string): UnoState {
  const s = clone(state);
  const i = requireTurn(s, playerId, 'playing');
  if (s.drawn === null) fail('Draw a card first');
  s.unoPending = null;
  s.drawn = null;
  log(s, { kind: 'pass', playerId });
  s.current = step(s, i);
  return s;
}

/** Call the bluff on a Wild Draw Four aimed at you. */
export function challengeDrawFour(state: UnoState, playerId: string, rng: Rng = Math.random): UnoState {
  const s = clone(state);
  const i = requireTurn(s, playerId, 'challenge');
  const { fromId, bluffing } = s.challenge!;
  s.unoPending = null;
  log(s, { kind: 'challenge', challengerId: playerId, targetId: fromId, bluffing });
  s.challenge = null;
  s.phase = 'playing';
  if (bluffing) {
    drawInto(s, indexOf(s, fromId), 4, 'challenge', rng); // caught: they take the 4, you play on
    s.current = i;
  } else {
    drawInto(s, i, 6, 'challenge', rng); // wrongly accused: you take 6 and lose your turn
    s.current = step(s, i);
  }
  return s;
}

/**
 * Press UNO. Allowed any time you hold one or two cards: calling with two covers you for the play that drops
 * you to one, and calling right after dropping to one clears the Catch window.
 */
export function callUno(state: UnoState, playerId: string): UnoState {
  const s = clone(state);
  const p = s.players[indexOf(s, playerId)]!;
  if (s.phase === 'roundOver' || s.phase === 'gameOver') fail('The round is over');
  if (p.hand.length > 2) fail('You can only call UNO with one or two cards left');
  p.calledUno = true;
  if (s.unoPending === playerId) s.unoPending = null;
  log(s, { kind: 'uno', playerId });
  return s;
}

/** Catch someone who forgot to call UNO, before the next player has acted. They draw 2. */
export function catchUno(state: UnoState, catcherId: string, rng: Rng = Math.random): UnoState {
  const s = clone(state);
  indexOf(s, catcherId);
  const targetId = s.unoPending;
  if (!targetId) fail('Nobody to catch');
  if (targetId === catcherId) fail("You can't catch yourself");
  s.unoPending = null;
  log(s, { kind: 'catch', catcherId, targetId: targetId! });
  drawInto(s, indexOf(s, targetId!), 2, 'catch', rng);
  return s;
}

/**
 * Ends the current player's turn without them acting (host skip, or an absent player's timeout).
 * Facing a Wild Draw Four this counts as accepting it.
 */
export function skipTurn(state: UnoState, rng: Rng = Math.random): UnoState {
  if (state.phase === 'roundOver' || state.phase === 'gameOver') fail('The round is over');
  const s = clone(state);
  const i = s.current;
  const player = s.players[i]!;
  s.unoPending = null;
  if (s.phase === 'challenge') {
    drawInto(s, i, 4, 'draw4', rng);
    s.challenge = null;
    s.phase = 'playing';
  }
  s.drawn = null;
  log(s, { kind: 'draw', playerId: player.id, count: 0, reason: 'skipped' });
  s.current = step(s, i);
  return s;
}

// ---- scoring ---------------------------------------------------------------

function finishRound(s: UnoState, winnerIndex: number) {
  const winner = s.players[winnerIndex]!;
  const points = s.players.reduce((sum, p) => sum + (p === winner ? 0 : p.hand.reduce((a, c) => a + cardPoints(c), 0)), 0);
  winner.score += points;
  s.roundWinnerId = winner.id;
  s.roundPoints = points;
  s.unoPending = null;
  s.drawn = null;
  s.challenge = null;
  log(s, { kind: 'round', winnerId: winner.id, points });
  if (winner.score >= s.settings.targetScore) {
    s.phase = 'gameOver';
    s.gameWinnerId = winner.id;
  } else {
    s.phase = 'roundOver';
  }
}

// ---- what a phone gets -----------------------------------------------------

export interface UnoView {
  phase: UnoPhase;
  round: number;
  targetScore: number;
  you: { id: string; hand: UnoCard[]; calledUno: boolean };
  /** Cards you can play right now (highlight these, dim the rest). */
  playable: number[];
  top: UnoCard;
  activeColor: UnoColor | null;
  direction: 1 | -1;
  currentPlayerId: string;
  drawPileCount: number;
  canDraw: boolean;
  /** You drew a playable card and may play it or pass. */
  canPass: boolean;
  /** Counts only; never other players' cards. `uno` drives the UNO! badge. */
  players: { id: string; cardCount: number; score: number; uno: boolean }[];
  /** A Wild Draw Four is waiting on `targetId`. Whether it was a bluff is NOT included. */
  challenge: { fromId: string; targetId: string } | null;
  /** Show the Catch! button for this player. */
  catchable: string | null;
  roundWinnerId: string | null;
  roundPoints: number;
  gameWinnerId: string | null;
  log: UnoEvent[];
}

/** The only thing a player's phone receives: their own hand plus public table info. */
export function unoViewFor(state: UnoState, playerId: string, logLines = 12): UnoView {
  const me = state.players[indexOf(state, playerId)]!;
  const playing = state.phase === 'playing' && state.players[state.current]!.id === playerId;
  return {
    phase: state.phase,
    round: state.round,
    targetScore: state.settings.targetScore,
    you: { id: me.id, hand: me.hand, calledUno: me.calledUno },
    playable: legalPlays(state, playerId),
    top: topCard(state),
    activeColor: state.activeColor,
    direction: state.direction,
    currentPlayerId: state.players[state.current]!.id,
    drawPileCount: state.drawPile.length,
    canDraw: (playing && state.drawn === null) || (state.phase === 'challenge' && state.challenge?.targetId === playerId),
    canPass: playing && state.drawn !== null,
    players: state.players.map((p) => ({ id: p.id, cardCount: p.hand.length, score: p.score, uno: p.hand.length === 1 })),
    challenge: state.challenge ? { fromId: state.challenge.fromId, targetId: state.challenge.targetId } : null,
    catchable: state.unoPending,
    roundWinnerId: state.roundWinnerId,
    roundPoints: state.roundPoints,
    gameWinnerId: state.gameWinnerId,
    log: state.log.slice(-logLines),
  };
}
